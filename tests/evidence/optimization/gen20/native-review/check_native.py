#!/usr/bin/env python3
"""Inspect retained generation 20 C and linked assembly; no native execution."""
import sys
sys.dont_write_bytecode = True
from pathlib import Path
from datetime import datetime, timezone
from collections import Counter
import hashlib, json, re

R = Path('tests/evidence/optimization/gen20/native-review')
P = 'lp_lean1090_Lean1090_Impl_'
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
load = lambda p: json.loads(Path(p).read_text())
capture = load(R / 'native-inputs.json')
build = load(R.parent / 'integration/targeted-build.json')
checks = []
bindings = {}
def check(ok, note):
    assert ok, note
    checks.append(note)
def bind(p, expected=None):
    h = sha(p)
    check(expected is None or h == expected, 'bound ' + str(p))
    bindings[str(p)] = h
    return h
def cbody(symbol):
    row = capture['generated_c_excerpts'][symbol]
    bind(row['path'], row['sha256']); bind(row['source'], row['source_sha256'])
    return '\n'.join(re.sub(r'^\d+: ', '', l) for l in Path(row['path']).read_text().splitlines())
def asm(symbol):
    path = R / 'native-inspection' / (symbol + '.txt')
    bind(path)
    rows = []
    for line in path.read_text().splitlines():
        m = re.match(r'\s*([0-9a-f]+):\s+(\S+)\s*(.*)', line)
        if m:
            rows.append(dict(address=int(m[1],16), mnemonic=m[2], operands=m[3]))
    check(bool(rows), 'actual linked body ' + symbol)
    return rows
def targets(rows):
    return [m[1] for r in rows if r['mnemonic'] in ('call','jmp') and (m := re.search(r'<([^>]+)>', r['operands']))]
def text(rows):
    return '\n'.join(r['mnemonic'] + ' ' + r['operands'] for r in rows)

bind(R / 'native-inputs.json')
bind(R.parent / 'integration/targeted-build.json', capture['integration_record_sha256'])
bind(R.parent / 'integration/targeted-build.log', build['log_sha256'])
check(build['status']=='passed' and build['exit_code']==0, 'combined build passed')
check(len(build['all_inputs_after'])==195 and build['all_inputs_before']==build['all_inputs_after'], '195 unchanged correctness inputs')
for path,h in capture['held_inputs'].items(): check(sha(path)==h, 'held ' + path)
check(capture['worker_sha256']==build['binary_hashes']['lean1090-bench'], 'actual linked worker equals integrated worker')
for row in capture['commands']:
    check(row['exit_code']==0 and not row['stderr'], 'static command succeeded: ' + row['output'])
    bind(row['output'], row['sha256'])
oldpath = Path('tests/evidence/optimization/gen19/native-review/native-inputs-complete.json')
bind(oldpath)
old = {r['source']:r for r in load(oldpath)['linked_inventory']}
differences = {}
for row in capture['linked_inventory']:
    differences[row['source']] = [key for key in ('source_sha256','c_sha256','object_sha256','trace_sha256') if row[key] != old[row['source']][key]]
check(len(differences)==22 and [s for s,d in differences.items() if d]==['Impl/Parity.lean'], 'only Parity differs across 22 source/C/object/trace sets')

byte_loop = next(s for s in capture['present_symbols'] if 'Parity_syndromeBytes_spec__0___redArg' in s)
bit_loop = next(s for s in capture['present_symbols'] if 'Parity_syndromeBits_spec__0___redArg' in s)
bc, oc = cbody(byte_loop), cbody(bit_loop)
check(bc.count('lean_uint32_xor(')==8 and bc.count('lean_uint32_shift_left(')==8, 'generated byte loop contains eight inlined UInt32 updates')
check(bc.count('goto _start;')==1 and bc.count('return ')==1, 'one byte-loop recurrence and one base return in generated C')
check(not any(x in bc for x in ['l_Nat_testBit(', 'lean_nat_shiftr(', 'lean_alloc_ctor(', 'Parity_wordStep(', 'Parity_byteStep(', 'Parity_cachedByte(']), 'byte core is inline and uses cached machine words without per-bit calls/list construction')
check('lean_nat_mul(' in bc and 'lean_unsigned_to_nat(8u)' in bc and 'lean_unsigned_to_nat(64u)' in bc, 'byte offset is eight times descending byte index with cache boundary')
check(bc.count('lean_uint64_shift_right(')==9, 'seven within-byte shifts plus two mutually exclusive cache shifts')
check('l_Nat_testBit(' in oc and oc.count('lean_uint32_xor(')==1, 'bit fallback retains arbitrary-natural bit extraction and one update')
syndrome = cbody(P+'Parity_syndrome')
check('lean_unsigned_to_nat(128u)' in syndrome and 'lean_nat_dec_le(' in syndrome and 'lean_nat_mod(' in syndrome and 'lean_unsigned_to_nat(8u)' in syndrome, 'public exact width and byte-alignment guard retained')
check(syndrome.count(P+'Parity_syndromeBits(')==2 and syndrome.count(P+'Parity_syndromeBytes(')==1, 'two mutually exclusive failing guards use original bit path; accepted guard uses byte path')
check('lean_unsigned_to_nat(3u)' in syndrome and 'lean_nat_shiftr(' in syndrome, 'width/8 becomes exact natural shift by three')
byte_wrapper = cbody(P+'Parity_syndromeBytes')
check(byte_wrapper.count(byte_loop+'(')==1 and 'lean_unsigned_to_nat(64u)' in byte_wrapper and 'l_BitVec_ofNat(' in byte_wrapper, 'byte wrapper caches low/high once, initializes zero and projects to 24 bits')
for name in ['Parity_wordStep','Parity_step','Parity_wordBit','Parity_cachedBit','Parity_byteStep','Parity_cachedByte','Parity_interrogator']:
    cbody(P+name)
init = cbody('initialize_lean1090_Impl_Parity')
check(not any(s in init for s in ['array','Array','byteStep','syndromeBytes']), 'no new CRC table or eager loop initialization')

loop_rows = asm(byte_loop)
first = next(i for i,r in enumerate(loop_rows) if r['mnemonic']=='shr' and r['operands']=='$0x7,%ecx')
last = next(i for i,r in enumerate(loop_rows[first:],first) if r['mnemonic']=='and' and r['operands']=='$0xffffff,%ebp')
unrolled = loop_rows[first:last+1]
check(not any(r['mnemonic'].startswith('j') or r['mnemonic']=='call' for r in unrolled), 'actual eight-update block is straight-line with no per-bit branch or call')
shifts = [r['operands'].split(',')[0] for r in unrolled if r['mnemonic']=='shr']
check(shifts==['$0x7','$0x6','$0x5','$0x4','$0x3','$0x2','$1'], 'actual bits consumed in order 7 through 1 then low bit 0')
for mnemonic,operand in [('xor','$0xfff409,'),('test','$0x800000,'),('and','$0xffffff,')]:
    check(sum(r['mnemonic']==mnemonic and r['operands'].startswith(operand) for r in unrolled)==8, 'eight native '+mnemonic+' '+operand)
check(sum(r['mnemonic']=='cmove' for r in unrolled)==8 and sum(r['mnemonic']=='lea' for r in unrolled)==8, 'eight native feedback selections and remainder doublings')
check('and $0x1,%eax' in text(unrolled), 'eighth update uses unshifted low bit')
check('shr %cl,%rax' in text(loop_rows) and 'mov (%rsp),%rax' in text(loop_rows) and 'mov 0x8(%rsp),%rax' in text(loop_rows), 'both actual cached halves converge on the same unrolled block')
check('l_Nat_testBit' not in targets(loop_rows), 'actual byte loop has no arbitrary-Nat testBit call')
fallback_rows = asm(bit_loop)
check('l_Nat_testBit' in targets(fallback_rows) and '$0x101' in text(fallback_rows), 'actual fallback retains indices at/above 128 through natural testBit')
guard_rows = asm(P+'Parity_syndrome')
check(P+'Parity_syndromeBytes' in targets(guard_rows) and P+'Parity_syndromeBits' in targets(guard_rows), 'actual guard reaches both live paths')
check('cmp $0x101,%rdi' in text(guard_rows) and 'and $0xf,%ebx' in text(guard_rows) and 'shr $0x3,%rdi' in text(guard_rows), 'actual tagged-Nat <=128/alignment/byte-count instructions present')

# Check that the two ownership-specialized loop call sites cannot both occur
# on one invocation. Internal branch traversal has no decoder execution.
wrapper_rows = asm(P+'Parity_syndromeBytes')
by_addr = {r['address']:i for i,r in enumerate(wrapper_rows)}
pending=[(0,0)];seen=set();terminal_counts=set();call_sites=[]
while pending:
    i,n=pending.pop()
    if (i,n) in seen: continue
    seen.add((i,n));r=wrapper_rows[i]
    if r['mnemonic']=='call' and '<'+byte_loop+'>' in r['operands']:
        n+=1;call_sites.append(r['address'])
    check(n<=1, 'wrapper path at most one byte-loop entry: '+hex(r['address']))
    m=re.match(r'([0-9a-f]+) ',r['operands']) if r['mnemonic'].startswith('j') else None
    target=int(m[1],16) if m else None
    if r['mnemonic']=='ret' or (r['mnemonic']=='jmp' and target not in by_addr):
        terminal_counts.add(n);continue
    if r['mnemonic'].startswith('j'):
        check(target in by_addr, 'internal conditional target retained')
        pending.append((by_addr[target],n))
        if r['mnemonic']=='jmp':continue
    if i+1<len(wrapper_rows):pending.append((i+1,n))
check(terminal_counts=={1} and len(set(call_sites))==2, 'two ownership sites represent exactly one dynamic byte fold per call')

for parent,child in [('decode','frameSyndrome'),('frameSyndrome','Parity_checksum'),('Parity_checksum','Parity_syndrome')]:
    body=cbody(P+parent)
    check(body.count(P+child+'(')==1, 'generated live path '+parent+' -> '+child)
    check(P+child in targets(asm(P+parent)), 'linked live path '+parent+' -> '+child)
check('Impl.Parity.syndrome' in Path('Tests/Upstream.lean').read_text(), 'frozen CRC adapter reaches public live syndrome')

for path in ['independent-review/source-proof-review.json','independent-review/byte-bit-proof-review.json','byte-bits-proof/summary.json','fold-proof/summary.json','byte-integration/summary.json']:
    bind(R.parent/path)
check(not load(R.parent/'independent-review/source-proof-review.json')['findings'], 'independent other-author source/proof assessment passed')
check(not load(R.parent/'independent-review/byte-bit-proof-review.json')['findings'], 'separate root review covers reviewer-authored helper')
context = dict(byte_loop_anchor=byte_loop, bit_loop_anchor=bit_loop, worker_sha256=capture['worker_sha256'], unrolled_instructions=unrolled, byte_bit_order=list(range(7,-1,-1)), native_polynomial_after_mask='0xfff409', final_mask='0xffffff', wrapper_call_sites=[hex(a) for a in sorted(set(call_sites))], wrapper_terminal_loop_counts=sorted(terminal_counts), source_native_differences=differences)
context_path=R/'byte-native-context.json';assert not context_path.exists();context_path.write_text(json.dumps(context,indent=2)+'\n');bind(context_path)
for path,h in capture['held_inputs'].items():check(sha(path)==h,'final held '+path)
files={str(p):dict(sha256=sha(p),bytes=p.stat().st_size) for p in sorted(R.rglob('*')) if p.is_file() and p.name not in ['review.json','review-01.log']}
out=dict(status='passed',findings=[],reviewed_utc=datetime.now(timezone.utc).isoformat(),checks_passed=len(checks),checks=checks,bindings=bindings,files=files,held_inputs=capture['held_inputs'],held_input_count=len(capture['held_inputs']),linked_native_sets=len(capture['linked_inventory']),all_inputs_unchanged=True,byte_crc_live_path_verified=True,byte_loop_anchor=byte_loop,bit_loop_anchor=bit_loop,worker=capture['worker'],worker_sha256=capture['worker_sha256'],integration_record_sha256=capture['integration_record_sha256'],unchanged_sibling_native_sets=21,source_delta=['Impl/Parity.lean'],native_context_sha256=sha(context_path),limitations=['This static review establishes live generated and linked paths, not a throughput or dynamic corpus-frequency measurement.', 'Inline wordStep/wordBit/byteStep/cachedByte wrappers are absent from the linked executable; their complete live work is visible in the retained fold.', 'Two native ownership call sites in syndromeBytes are mutually exclusive; the generated C has one fold call and every linked terminal path traverses one site.', 'The fold retains general Nat index arithmetic and related slow/ownership paths. No claim of an entirely allocation-free decoder or loop is made.', 'Proofs/ParityByteBits was authored by this reviewer and is independently covered by the bound root review. This reviewer independently assessed the runtime, FoldBlocks, composition and unchanged integration statements.'])
path=R/'review.json';assert not path.exists();path.write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps(dict(status='passed',checks=len(checks),held=len(capture['held_inputs']),linked_sets=len(capture['linked_inventory']),review_sha256=sha(path),context_sha256=sha(context_path))))
